"""Builds report.md: hardened prompt, final guard policy, metrics, OWASP findings, patch history."""

from __future__ import annotations

import json
from collections import Counter
from typing import TYPE_CHECKING

from kavach.models import FinalReport, TargetConfig
from kavach.scoring.metrics import owasp_breakdown

if TYPE_CHECKING:
    from kavach.orchestrator.run import RunState


def _pct(v) -> str:
    return "–" if v is None else f"{round(v * 100)}%"


def build_report(state: RunState, final: TargetConfig, fr: FinalReport) -> str:
    s = state.summary
    lines = [
        f"# Kavach audit report · {s.run_id}",
        "",
        "Target: **DiwaliMart Support** (tool-using support bot, fake data). Scores are computed in code from the target's tool-call log.",
        "",
        "## Executive summary",
        "",
        fr.executive_summary,
        "",
        "## Rounds",
        "",
        "| Round | Config attacked | Attacks | Breach rate | Findings | Attempts | Vetoes | Applied | Utility | Time to harden |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in s.rounds:
        found = ", ".join(f"{k} ×{v}" for k, v in r.findings_by_rule.items()) or "none"
        tth = f"{r.tth_seconds:.0f}s" if r.tth_seconds is not None else "–"
        lines.append(
            f"| {r.round} | {r.config_attacked} | {r.total_attacks} | {_pct(r.breach_rate)} | {found} | {r.attempts} | {r.vetoes} | {r.applied_version or '–'} | {_pct(r.utility_applied)} | {tth} |"
        )
    lines += ["", "## Findings by OWASP LLM Top 10 (2025)", "", "| Category | Count |", "|---|---|"]
    for k, v in sorted(owasp_breakdown(state.findings).items()):
        lines.append(f"| {k} | {v} |")
    by_rule = Counter(f.rule_id for f in state.findings)
    lines += ["", "| Rule | Count |", "|---|---|"] + [f"| {k} | {v} |" for k, v in by_rule.most_common()]
    if fr.top_risks:
        lines += ["", "## Top risks", ""] + [
            f"- **{t.title}** ({t.owasp}, {t.status}): {t.detail}" for t in fr.top_risks
        ]
    if state.findings:
        lines += ["", "## Evidence (first 12 findings)", ""]
        for f in state.findings[:12]:
            lines.append(
                f"- `{f.attack_id}` · {f.rule_id} ({f.severity}) · technique `{f.technique}`: {f.evidence}"
            )
    lines += ["", "## Patch history", ""]
    if state.patch_history:
        for p in state.patch_history:
            lines.append(f"### {p['version']} (round {p['round']})")
            lines += [f"- {c}" for c in p["changelog"]] + [""]
    else:
        lines.append("No patches were applied.")
    lines += ["", "## Recommendations", ""] + [f"- {r}" for r in fr.recommendations]
    lines += [
        "",
        f"## Hardened system prompt ({final.version})",
        "",
        "````text",
        final.system_prompt,
        "````",
        "",
        f"## Final guard policy ({final.version})",
        "",
        "```json",
        json.dumps(final.guard_policy.model_dump(), indent=2),
        "```",
        "",
        "---",
        "Generated by Kavach · Lyzr · Band · Agent37 · AdaL",
    ]
    return "\n".join(lines)
